# ── /api/chat 包装层（假图 monkeypatch） ────────────────────────

@pytest.fixture
def chat_client(monkeypatch):
    """graph 替换为假图的 TestClient（不触发 lifespan：mcp 端点
    会 503，本夹具只测 chat 路径，无关）"""
    fake = FakeGraph()
    monkeypatch.setattr("api.main.graph", fake)
    return TestClient(app), fake


def test_chat_write_through_and_thread_binding(chat_client):
    client, fake = chat_client
    r = client.post("/api/chat", json={
        "message": "问题", "user_id": "u9", "session_id": "sess_write",
    })
    assert r.status_code == 200
    body = r.json()
    assert body["response"] == "存根回复"
    assert body["session_id"] == "sess_write"  # 透传
    assert body["intent"] == "knowledge_rag"   # 结果映射

    # 假图收到的调用：initial_state 组装 + thread_id 绑定
    assert len(fake.invocations) == 1
    inv = fake.invocations[0]
    assert inv["config"]["configurable"]["thread_id"] == "sess_write"
    assert inv["state"]["user_id"] == "u9"
    assert inv["state"]["messages"][0].content == "问题"

    # 写透：user 先写、assistant 后写（模块级 STM 单例）
    history = client.get("/api/history/sess_write").json()["messages"]
    assert [(m["role"], m["content"]) for m in history] == [
        ("user", "问题"), ("assistant", "存根回复"),
    ]


def test_chat_session_id_autogenerated(chat_client):
    client, fake = chat_client
    r = client.post("/api/chat", json={"message": "问题"}).json()
    assert r["session_id"]  # 服务端新建并回传
    assert fake.invocations[0]["config"]["configurable"]["thread_id"] == r["session_id"]


def test_chat_failure_leaves_unanswered_user_message(chat_client, monkeypatch):
    # 失败窗口语义：user 已写、assistant 无（2.1 设计决策）+ 500 通用文案
    monkeypatch.setattr("api.main.graph", FakeGraph(error=RuntimeError("LLM down")))
    client = TestClient(app)
    r = client.post("/api/chat", json={
        "message": "会失败的问题", "session_id": "sess_fail",
    })
    assert r.status_code == 500
    assert "处理失败" in r.json()["detail"]
    history = client.get("/api/history/sess_fail").json()["messages"]
    assert [(m["role"], m["content"]) for m in history] == [("user", "会失败的问题")]


